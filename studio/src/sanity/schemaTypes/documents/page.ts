import { defineField, defineType } from 'sanity'
import { EditIcon, ErrorScreenIcon, HomeIcon, SearchIcon } from '@sanity/icons'
import { VscEyeClosed } from 'react-icons/vsc'
import modules from '../fragments/modules'
import EditorialChecklistBanner from '@/sanity/ui/editorial-checklist-banner'

const modulesField = modules({ enableTemplateStore: true })

export default defineType({
	name: 'page',
	title: 'Page',
	type: 'document',
	groups: [
		{ name: 'content', title: 'Content', default: true },
		{ name: 'appearance', title: 'Appearance & Canvas' },
		{ name: 'metadata', title: 'Metadata & SEO' },
	],
	fields: [
		defineField({
			name: 'title',
			type: 'string',
			group: 'content',
			validation: (Rule) => Rule.required(),
		}),
		defineField({
			name: 'editorialChecklist',
			title: 'AI Editorial Handoff Checklist',
			description: 'Setup checklist generated by AI Agent for manual finishing tasks.',
			type: 'array',
			group: 'content',
			components: {
				input: EditorialChecklistBanner,
			},
			of: [
				{
					type: 'object',
					name: 'checklistItem',
					fields: [
						defineField({ name: 'step', type: 'number' }),
						defineField({ name: 'targetLocation', type: 'string' }),
						defineField({ name: 'targetTab', type: 'string' }),
						defineField({ name: 'targetPath', type: 'string' }),
						defineField({ name: 'actionRequired', type: 'string' }),
						defineField({ name: 'guidelines', type: 'text', rows: 2 }),
						defineField({ name: 'suggestedAltText', type: 'string' }),
						defineField({ name: 'completed', type: 'boolean', initialValue: false }),
					],
				},
			],
		}),
		defineField({
			name: 'appearance',
			title: 'Page Appearance & Atmosphere',
			type: 'page-appearance',
			group: 'appearance',
		}),
		defineField({
			...modulesField,
			group: 'content',
		}),
		defineField({
			name: 'metadata',
			type: 'metadata',
			group: 'metadata',
		}),
	],
	preview: {
		select: {
			title: 'title',
			slug: 'metadata.slug.current',
			noIndex: 'metadata.noIndex',
		},
		prepare: ({ title, slug, noIndex }) => ({
			title,
			subtitle: `/${slug === 'index' ? '' : slug}`,
			media:
				(slug === 'index' && HomeIcon) ||
				(slug === '404' && ErrorScreenIcon) ||
				(slug === 'search' && SearchIcon) ||
				(slug === 'blog' && EditIcon) ||
				(noIndex && VscEyeClosed),
		}),
	},
})
